use std::{
    fs,
    path::PathBuf,
    sync::atomic::{AtomicUsize, Ordering},
};

use okf_adapter_fs::{
    generated_blocks::{GENERATED_END, GENERATED_START, replace_generated, validate_generated},
    instructions, templates,
};
use okf_application::lifecycle::LifecycleFs;

struct Scratch(PathBuf);
impl Scratch {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let path = std::env::temp_dir().join(format!(
            "okf-generated-{}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir(&path).unwrap();
        Self(path)
    }
}
impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

#[test]
fn generated_replacement_preserves_curated_text_and_rejects_malformed_markers() {
    let original = format!(
        "# Title\n\nCurated before.\n\n{GENERATED_START}\nold generated\n{GENERATED_END}\n\nCurated after.\n"
    );
    let replaced = replace_generated(&original, "new generated");
    assert!(replaced.contains("Curated before."));
    assert!(replaced.contains("Curated after."));
    assert!(replaced.contains("new generated"));
    assert!(!replaced.contains("old generated"));
    assert!(replace_generated(&replaced, "new generated") == replaced);
    assert!(
        validate_generated(
            &format!("{GENERATED_START}\n{GENERATED_START}\n"),
            ".okf/test.md"
        )
        .is_err()
    );
}

#[test]
fn initialization_preserves_partial_curated_files_and_installs_selected_profiles() {
    let scratch = Scratch::new();
    fs::create_dir_all(scratch.0.join(".okf/architecture")).unwrap();
    fs::write(
        scratch.0.join(".okf/architecture/index.md"),
        "# Curated architecture\n",
    )
    .unwrap();
    let created = templates::initialize(&scratch.0, &["sdd".to_owned()]).unwrap();
    assert!(created.contains(&".okf/manifest.yaml".to_owned()));
    assert_eq!(
        fs::read_to_string(scratch.0.join(".okf/architecture/index.md")).unwrap(),
        "# Curated architecture\n"
    );
    assert!(scratch.0.join(".okf/workflows/profiles/sdd.md").is_file());
    assert!(scratch.0.join(".okf-index").is_dir());
}

#[test]
fn initialization_ignores_local_index_and_preserves_existing_gitignore_content() {
    let scratch = Scratch::new();
    fs::write(scratch.0.join(".gitignore"), "build/\r\nuser-data/\r\n").unwrap();

    templates::initialize(&scratch.0, &[]).unwrap();
    templates::initialize(&scratch.0, &[]).unwrap();

    let gitignore = fs::read_to_string(scratch.0.join(".gitignore")).unwrap();
    assert!(gitignore.starts_with("build/\r\nuser-data/\r\n"));
    assert!(gitignore.contains(".okf-index/\r\n"));
    assert_eq!(gitignore.matches(".okf-index/").count(), 1);
}

#[test]
fn adapter_install_keeps_curated_instructions_and_non_okf_hooks() {
    let scratch = Scratch::new();
    let git = scratch.0.join(".git");
    let hooks = git.join("hooks");
    fs::create_dir_all(&hooks).unwrap();
    fs::write(
        scratch.0.join("AGENTS.md"),
        "# Project instructions\n\nKeep this text.\n",
    )
    .unwrap();
    fs::write(hooks.join("pre-commit"), "#!/bin/sh\necho user hook\n").unwrap();
    fs::write(
        hooks.join("pre-push"),
        "#!/bin/sh\n# Generated by okf-agent\nold hook\n",
    )
    .unwrap();
    let report = instructions::install(&scratch.0, Some(&git), false).unwrap();
    let agents = fs::read_to_string(scratch.0.join("AGENTS.md")).unwrap();
    assert!(agents.contains("Keep this text."));
    assert!(agents.contains("OKF Repository Protocol"));
    assert!(
        fs::read_to_string(hooks.join("pre-commit"))
            .unwrap()
            .contains("user hook")
    );
    assert!(
        fs::read_to_string(hooks.join("pre-push"))
            .unwrap()
            .contains("okf-agent validate .")
    );
    assert!(report.installed.contains(&"AGENTS.md".to_owned()));
}

#[test]
fn validation_reports_bad_manifest_and_links_that_escape_the_root() {
    let scratch = Scratch::new();
    templates::initialize(&scratch.0, &[]).unwrap();
    fs::write(
        scratch.0.join(".okf/manifest.yaml"),
        "schema_version: 2\nname: broken\n",
    )
    .unwrap();
    fs::write(
        scratch.0.join(".okf/operations/development.md"),
        "# Development\n[escape](../../../outside.md)\n",
    )
    .unwrap();
    let report = okf_adapter_fs::lifecycle::FsLifecycle
        .validate_files(&scratch.0)
        .unwrap();
    assert!(!report.ok);
    assert!(
        report
            .errors
            .iter()
            .any(|error| error.contains("manifest.yaml"))
    );
    assert!(
        report
            .errors
            .iter()
            .any(|error| error.contains("escapes repository"))
    );
}
